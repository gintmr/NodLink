const listeners = new Set();
let lang = (() => {
  try {
    const saved = JSON.parse(localStorage.getItem('nodlink.lang'));
    if (saved === 'zh' || saved === 'en') return saved;
  } catch { /* 隐私模式下忽略 */ }
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
})();

export const getLang = () => lang;

export function t(zh, vars) {
  let s = lang === 'en' ? EN[zh] ?? zh : zh;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return s;
}

export function onLangChange(fn) {
  listeners.add(fn);
}

export function setLang(next) {
  lang = next;
  try { localStorage.setItem('nodlink.lang', JSON.stringify(next)); } catch { /* 隐私模式下忽略 */ }
  translateDom();
  for (const fn of listeners) fn();
}

// 页面里写死的文字：记住每个文字节点和属性的中文原文，切换语言时从原文重新翻译
const originals = new WeakMap();
const HAN = /[一-鿿]/;

export function translateDom(root = document.body) {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement?.closest('script, style, [data-no-i18n]')) continue;
    if (!originals.has(node)) {
      if (!HAN.test(node.nodeValue)) continue;
      originals.set(node, node.nodeValue);
    }
    const orig = originals.get(node);
    const key = orig.trim();
    node.nodeValue = orig.replace(key, t(key));
  }
  for (const el of root.querySelectorAll('[aria-label]')) {
    el.dataset.zhLabel ??= el.getAttribute('aria-label');
    if (HAN.test(el.dataset.zhLabel)) el.setAttribute('aria-label', t(el.dataset.zhLabel));
  }
}

/** 每个字占 6 列（5 列字形加 1 列间隔） */
export const pixelTextWidth = (str, size) => (str.length * 6 - 1) * size;

/** 能完整画出来的字符串（先转成大写） */
export const pixelSafe = (str) => [...str.toUpperCase()].every((ch) => ch in GLYPHS);

export function drawPixelText(g, str, x, y, size, color) {
  g.fillStyle = color;
  [...str.toUpperCase()].forEach((ch, i) => {
    (GLYPHS[ch] ?? GLYPHS[' ']).forEach((row, ry) => {
      for (let rx = 0; rx < 5; rx++) if (row[rx] === '1') g.fillRect(Math.round(x + (i * 6 + rx) * size), Math.round(y + ry * size), size, size);
    });
  });
}

/** 显示器标题栏的文字：编号必有；名称能画出来、放得下才画，放不下就截短 */
export function screenTitle(screen, maxChars) {
  const no = `${screen.no ?? 1}`;
  const name = screen.name && pixelSafe(screen.name) ? screen.name.toUpperCase() : '';
  if (!name || maxChars < no.length + 4) return { no, name: '' };
  const room = maxChars - no.length - 1;
  return { no, name: name.length > room ? `${name.slice(0, room - 2).trimEnd()}..` : name };
}
